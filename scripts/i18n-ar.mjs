function setDirectTextPreservingElements($, el, newText) {
  if (!el || !el.length) return;
  if (el.children().length === 0) {
    el.text(newText);
    return;
  }
  let replaced = false;
  el.contents().each((_, node) => {
    if (node.type === 'text' && node.data && node.data.trim()) {
      if (!replaced) {
        node.data = ` ${newText} `;
        replaced = true;
      } else {
        node.data = '';
      }
    }
  });
  if (!replaced) {
    el.append(` ${newText}`);
  }
}

