export function translateText(raw) {
  if (!raw || typeof raw !== 'string') return raw;
  const trimmed = raw.trim().replace(/\s+/g, ' ');
  if (!trimmed) return raw;

  // Direct lookup (exact or normalized whitespace)
  const direct = AR_MAP[raw.trim()] || AR_MAP[trimmed];
  if (direct) {
    const lead = raw.match(/^\s*/)?.[0] || '';
    const trail = raw.match(/\s*$/)?.[0] || '';
    return `${lead}${direct}${trail}`;
  }

  // Dynamic patterns: e.g. "408 results" -> "408 نتيجة"
  const resultsMatch = trimmed.match(/^(\d+)\s+results$/i);
  if (resultsMatch) return `${resultsMatch[1]} نتيجة`;

  // Dynamic patterns: e.g. "06 July 2025" or "14 October 2026"
  const dateMatch = trimmed.match(/^(\d{1,2})\s+([A-Za-z]+)\s+(\d{4})$/);
  if (dateMatch && MONTHS_AR[dateMatch[2]]) {
    return `${dateMatch[1]} ${MONTHS_AR[dateMatch[2]]} ${dateMatch[3]}`;
  }

  // Dynamic file size: e.g. "50.6 mb" -> "50.6 ميجابايت"
  const sizeMatch = trimmed.match(/^([\d.]+)\s*mb$/i);
  if (sizeMatch) return `${sizeMatch[1]} ميجابايت`;

  // Dynamic Instagram post aria-label
  if (trimmed.startsWith('Open Instagram post:')) {
    return 'عرض منشور إنستغرام';
  }

  return raw;
}

export function toArRoute(enRoute) {
  if (!enRoute || typeof enRoute !== 'string') return enRoute;
  if (enRoute === '/en/' || enRoute === '/en') return '/ar/';
  if (enRoute.startsWith('/en/')) return '/ar/' + enRoute.slice(4);
  return enRoute;
}

