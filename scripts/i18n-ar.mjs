export function localizeDomToArabic($, enRoute = '') {
  // 1. Rewrite internal /en/... links to /ar/...
  $('a[href]').each((_, el) => {
    const a = $(el);
    const href = a.attr('href') || '';
    // Skip the language switcher link that explicitly points back to English
    if (a.attr('hreflang') === 'en') return;
    if (href === '/en/' || href === '/en') {
      a.attr('href', '/ar/');
    } else if (href.startsWith('/en/')) {
      a.attr('href', '/ar/' + href.slice(4));
    } else if (href.startsWith('?search=')) {
      const q = decodeURIComponent(href.slice(8));
      const arQ = translateText(q);
      a.attr('href', `?search=${encodeURIComponent(arQ)}`);
    }
    // Ensure phone, mailto, and website URLs keep LTR direction inside RTL layout
    if (
      href.startsWith('tel:') ||
      href.startsWith('mailto:') ||
      href.includes('jaralbait.com')
    ) {
      a.attr('dir', 'ltr');
    }
  });

  // 2. Localize data-local-map & data-map-config JSON on homepage map
  $('[data-local-map]').each((_, el) => {
    const mapEl = $(el);
    try {
      const cfg = JSON.parse(mapEl.attr('data-local-map'));
      if (cfg.image === '/assets/jar-al-bait-hotels-map.svg') {
        cfg.image = '/assets/jar-al-bait-hotels-map-ar.svg';
      }
      if (cfg.label) cfg.label = translateText(cfg.label);
      if (Array.isArray(cfg.markers)) {
        cfg.markers = cfg.markers.map((m) => ({
          ...m,
          name: translateText(m.name),
          city: translateText(m.city)
        }));
      }
      mapEl.attr('data-local-map', JSON.stringify(cfg));
    } catch {}
  });

  $('[data-map-config]').each((_, el) => {
    const mapEl = $(el);
    try {
      const cfg = JSON.parse(mapEl.attr('data-map-config'));
      if (Array.isArray(cfg.items)) {
        cfg.items = cfg.items.map((item) => ({
          ...item,
          tooltip_label: translateText(item.tooltip_label),
          tooltip_title: translateText(item.tooltip_title)
        }));
      }
      mapEl.attr('data-map-config', JSON.stringify(cfg));
    } catch {}
  });

  // 3. Translate translatable attributes
  const attrs = [
    'placeholder',
    'aria-label',
    'title',
    'alt',
    'data-submit-state',
    'data-text-show-less',
    'data-label-all-results',
    'data-label-link-result',
    'data-template'
  ];
  $('*').each((_, el) => {
    const node = $(el);
    for (const attr of attrs) {
      const val = node.attr(attr);
      if (val) {
        const translated = translateText(val);
        if (translated !== val) node.attr(attr, translated);
      }
    }
    if (el.name === 'meta' && node.attr('itemprop') === 'caption') {
      const val = node.attr('content');
      if (val) {
        const translated = translateText(val);
        if (translated !== val) node.attr('content', translated);
      }
    }
  });

  // 4. Walk and translate all text nodes
  function walk(nodes) {
    for (const node of nodes) {
      if (node.type === 'text') {
        const parentTag = node.parent?.name?.toLowerCase();
        if (parentTag === 'script' || parentTag === 'style') continue;
        const original = node.data;
        if (!original || !original.trim()) continue;
        const normalized = original.replace(/\u00a0/g, ' ');
        const translated = translateText(normalized);
        if (translated !== normalized) {
          const hasLeadingNbsp = /^\s*\u00a0/.test(original);
          const hasTrailingNbsp = /\u00a0\s*$/.test(original);
          const hasLeadingSpace = !hasLeadingNbsp && /^\s+/.test(original);
          const hasTrailingSpace = !hasTrailingNbsp && /\s+$/.test(original);
          node.data = `${hasLeadingNbsp ? '\u00a0' : hasLeadingSpace ? ' ' : ''}${translated.trim()}${hasTrailingNbsp ? '\u00a0' : hasTrailingSpace ? ' ' : ''}`;
        }
      } else if (node.children && node.children.length) {
        walk(node.children);
      }
    }
  }
  walk($.root().children());

  // 5. Apply authoritative official PDF overrides for Header, Newsletter, Footer, and Core Pages
  applyOfficialPdfArabicOverrides($, enRoute);
}
